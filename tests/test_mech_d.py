@pytest.mark.parametrize("name", ["lowkick_heavy", "lowkick_kingambit", "lowkick_light", "grassknot_heavy", "grassknot_light",
                                  "heatcrash_light", "heatcrash_heavy", "heavyslam_light", "heavyslam_mid"])
def test_weight_based_moves_match_the_calculator(name):
    c = case(name)
    attacker, move, defender, fs = _pair(c)
    est = battle.damage_percent(attacker, move, defender, field=fs, spread=c["spread_in_calc"])
    assert est is not None, "a weight-based move is a damage row, not a status move"
    assert error_vs_calc(c, est) < TOLERANCE, (name, est, c["damage"])
    assert battle.effective_move(attacker, move, defender, fs)["base_power"] == data.weight_power(move, defender, attacker)


def test_low_kick_lands_on_the_sheet():
    """Tyranitar's Low Kick into Kingambit (81-97%, invisible before Oct 8) is an option row for us and a threat row from them."""
    sheet, _ = build(["Tyranitar", "Amoonguss"], ["Kingambit", "Tyranitar"])
