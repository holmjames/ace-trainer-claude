    assert rain.switch_ins["greattusk"]["takes_worst"]["ko_chance"] == 1.0
    assert rain.switch_ins["greattusk"]["score"] < sheet.switch_ins["greattusk"]["score"]  # a surer KO on entry is a worse switch


