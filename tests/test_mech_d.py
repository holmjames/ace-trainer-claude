def test_is_spread_counts_who_is_there_to_hit():
    rock_slide, earthquake, moonblast = data.move_info("Rock Slide"), data.move_info("Earthquake"), data.move_info("Moonblast")
    assert battle.is_spread(rock_slide, foes=2) and not battle.is_spread(rock_slide, foes=1, allies=1)
    assert battle.is_spread(earthquake, foes=1, allies=1) and not battle.is_spread(earthquake, foes=1, allies=0)
    assert not battle.is_spread(moonblast, foes=2, allies=1)


def test_entry_hits_price_the_spread_modifier_and_the_field():
    single, doubles = case("spread_pivot_single"), case("spread_pivot_doubles")
    attacker, move, sneasler, fs = _pair(doubles)
    both = next(h for h in battle.entry_hits(attacker, sneasler, fs, our_actives=2, their_actives=2) if h["move"] == "earthquake")
    alone = next(h for h in battle.entry_hits(attacker, sneasler, fs, our_actives=1, their_actives=1) if h["move"] == "earthquake")
    assert error_vs_calc(doubles, both["damage_pct_of_current_hp"]) < TOLERANCE and both["ko"] != "guaranteed"
    assert error_vs_calc(single, alone["damage_pct_of_current_hp"]) < TOLERANCE and alone["ko"] == "guaranteed"
    # Rock Slide into our pair under sand with our Reflect up, and Dazzling Gleam through Light Screen into a Rock type in sand.
    for name in ("rockslide_spread_sand_reflect_tornadus", "rockslide_spread_sand_reflect_salamence",
                 "gleam_spread_sand_screen_tyranitar", "gleam_spread_sand_screen_kingambit"):
        c = case(name)
        attacker, move, defender, fs = _pair(c)
        fs.my_side, fs.their_side = fs.their_side, set()  # the incoming Pokémon is on OUR side in the preview
        incoming = replace(defender, side="mine", ability=None)  # the fixture has no Intimidate from the incoming side (Salamence has it)
        hit = next(h for h in battle.entry_hits(attacker, incoming, fs, our_actives=2, their_actives=2) if h["move"] == move["id"])
        assert error_vs_calc(c, hit["damage_pct_of_current_hp"]) < TOLERANCE, (name, hit)


