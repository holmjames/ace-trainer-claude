def test_switch_preview_ko_odds_include_accuracy():
    """Their Salamence's Hurricane knocks our benched Great Tusk out on entry 70% of the time; in rain, every time."""
    sheet, _ = build(["Amoonguss", "Cresselia"], ["Salamence", "Dondozo"], bench=["Great Tusk"])
    takes = sheet.switch_ins["greattusk"]["takes_worst"]
    assert takes["from"] == "Salamence" and takes["move"] == "hurricane"
    assert error_vs_calc(case("hurricane_ohko_salamence"), takes["damage_pct"]) < TOLERANCE
    assert takes["hit_chance"] == pytest.approx(0.7) and takes["ko_chance"] == pytest.approx(0.7)
